export type Copy = (typeof copy)[Locale];

function setPath(target: Record<string, unknown>, path: string, value: string) {
  const parts = path.split(".");
  let cursor: Record<string, unknown> = target;

  for (let index = 0; index < parts.length - 1; index += 1) {
    const part = parts[index];
    const next = cursor[part];
    if (!next || typeof next !== "object" || Array.isArray(next)) {
      return;
    }
    cursor = next as Record<string, unknown>;
  }

  const leaf = parts.at(-1);
  if (leaf && typeof cursor[leaf] === "string") {
    cursor[leaf] = value;
  }
}

export function getCopy(locale: Locale, overrides?: Record<string, string>): Copy {
  const base = structuredClone(copy[locale]) as Copy;
  if (!overrides) return base;

  for (const [key, value] of Object.entries(overrides)) {
    setPath(base as unknown as Record<string, unknown>, key, value);
  }

  return base;
}
